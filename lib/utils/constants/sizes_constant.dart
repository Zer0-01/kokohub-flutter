import 'package:flutter/widgets.dart';

class SizesConstant {
  SizesConstant._();

  // Height percentages
  static double height10(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.10;

  static double height20(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.20;

  static double height30(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.30;

  static double height40(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.40;

  static double height50(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.50;

  static double height60(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.60;

  static double height70(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.70;

  static double height80(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.80;

  static double height90(BuildContext context) =>
      MediaQuery.of(context).size.height * 0.90;

  static double height100(BuildContext context) =>
      MediaQuery.of(context).size.height;

  // Width percentages
  static double width10(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.10;

  static double width20(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.20;

  static double width30(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.30;

  static double width40(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.40;

  static double width50(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.50;

  static double width60(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.60;

  static double width70(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.70;

  static double width80(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.80;

  static double width90(BuildContext context) =>
      MediaQuery.of(context).size.width * 0.90;

  static double width100(BuildContext context) =>
      MediaQuery.of(context).size.width;
}
